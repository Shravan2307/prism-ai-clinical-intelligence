const LOGO_URL = "/prism-signal-logo.png";

const initialForm: PatientRequest = {
  age: 58,
  bmi: 28.4,
  hba1c: 7.2,
  fasting_glucose: 142,
  egfr: 78,
  systolic_bp: 132,
  diastolic_bp: 82,
  current_meds: [],
};

const medicationOptions = ["Metformin", "SGLT2i", "GLP-1", "ACE inhibitor", "ARB", "Statin"];

function fieldError(label: string, value: number, min: number, max: number) {
  if (!Number.isFinite(value)) return `${label} is required.`;
  if (value < min || value > max) return `${label} must be between ${min} and ${max}.`;
  return "";
}

function formatLabel(value: string) {
  return value.replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function statusTone(value: string) {
  const normalized = value.toLowerCase();
  if (normalized.includes("emergency") || normalized.includes("urgent") || normalized.includes("high")) return "danger";
  if (normalized.includes("moderate") || normalized.includes("review") || normalized.includes("attention")) return "attention";
  return "stable";
}

function Metric({ label, value, unit }: { label: string; value: string | number; unit?: string }) {
  return (
    <div className="metric-block">
      <p className="eyebrow">{label}</p>
      <p className="metric-value">{value}<span>{unit}</span></p>
    </div>
  );
}

function StatusBadge({ value }: { value: string }) {
  return <span className={`status-badge ${statusTone(value)}`}>{formatLabel(value)}</span>;
}

function PatientForm({
  form,
  setForm,
  onSubmit,
  loading,
  error,
}: {
  form: PatientRequest;
  setForm: (value: PatientRequest) => void;
  onSubmit: (event: FormEvent<HTMLFormElement>) => void;
  loading: boolean;
  error: string;
}) {
  const errors = useMemo(() => ({
    age: fieldError("Age", form.age, 18, 90),
    bmi: fieldError("BMI", form.bmi, 15, 60),
    hba1c: fieldError("HbA1c", form.hba1c, 4, 15),
    fasting_glucose: fieldError("Fasting glucose", form.fasting_glucose, 50, 350),
    egfr: fieldError("eGFR", form.egfr, 15, 150),
    systolic_bp: fieldError("Systolic blood pressure", form.systolic_bp, 90, 220),
    diastolic_bp: fieldError("Diastolic blood pressure", form.diastolic_bp, 50, 130),
  }), [form]);
  const hasErrors = Object.values(errors).some(Boolean) || form.diastolic_bp >= form.systolic_bp;

  const updateNumber = (key: keyof PatientRequest, value: string) => {
    const numeric = value === "" ? Number.NaN : Number(value);
    setForm({ ...form, [key]: numeric });
  };

  const toggleMedication = (medication: string) => {
    const current = form.current_meds.includes(medication)
      ? form.current_meds.filter((item) => item !== medication)
      : [...form.current_meds, medication];
    setForm({ ...form, current_meds: current });
  };

  return (
    <form className="intake-form" onSubmit={onSubmit} noValidate>
      <div className="section-heading">
        <div>
          <p className="eyebrow teal">Patient intake</p>
          <h2>Trace the signal before the next decision.</h2>
        </div>
        <span className="provenance"><ShieldCheck size={13} /> Backend validated</span>
      </div>
      <p className="section-copy">Enter the measurements available for this assessment. The analysis is generated by the connected clinical intelligence service.</p>

      {error && (
        <div className="error-banner" role="alert">
          <AlertTriangle size={18} />
          <div><strong>Analysis unavailable</strong><p>{error}</p></div>
        </div>
      )}

      <div className="form-grid">
        <label className="field"><span>Age <small>years</small></span><input aria-label="Age" type="number" min="18" max="90" value={Number.isNaN(form.age) ? "" : form.age} onChange={(e) => updateNumber("age", e.target.value)} />{errors.age && <em>{errors.age}</em>}</label>
        <label className="field"><span>BMI <small>kg/m²</small></span><input aria-label="BMI" type="number" step="0.1" min="15" max="60" value={Number.isNaN(form.bmi) ? "" : form.bmi} onChange={(e) => updateNumber("bmi", e.target.value)} />{errors.bmi && <em>{errors.bmi}</em>}</label>
        <label className="field"><span>HbA1c <small>%</small></span><input aria-label="HbA1c" type="number" step="0.1" min="4" max="15" value={Number.isNaN(form.hba1c) ? "" : form.hba1c} onChange={(e) => updateNumber("hba1c", e.target.value)} />{errors.hba1c && <em>{errors.hba1c}</em>}</label>
        <label className="field"><span>Fasting glucose <small>mg/dL</small></span><input aria-label="Fasting glucose" type="number" step="0.1" min="50" max="350" value={Number.isNaN(form.fasting_glucose) ? "" : form.fasting_glucose} onChange={(e) => updateNumber("fasting_glucose", e.target.value)} />{errors.fasting_glucose && <em>{errors.fasting_glucose}</em>}</label>
        <label className="field"><span>eGFR <small>mL/min/1.73m²</small></span><input aria-label="eGFR" type="number" step="0.1" min="15" max="150" value={Number.isNaN(form.egfr) ? "" : form.egfr} onChange={(e) => updateNumber("egfr", e.target.value)} />{errors.egfr && <em>{errors.egfr}</em>}</label>
        <label className="field"><span>Systolic BP <small>mmHg</small></span><input aria-label="Systolic blood pressure" type="number" step="0.1" min="90" max="220" value={Number.isNaN(form.systolic_bp) ? "" : form.systolic_bp} onChange={(e) => updateNumber("systolic_bp", e.target.value)} />{errors.systolic_bp && <em>{errors.systolic_bp}</em>}</label>
        <label className="field"><span>Diastolic BP <small>mmHg</small></span><input aria-label="Diastolic blood pressure" type="number" step="0.1" min="50" max="130" value={Number.isNaN(form.diastolic_bp) ? "" : form.diastolic_bp} onChange={(e) => updateNumber("diastolic_bp", e.target.value)} />{errors.diastolic_bp && <em>{errors.diastolic_bp}</em>}{form.diastolic_bp >= form.systolic_bp && <em>Must be lower than systolic BP.</em>}</label>
      </div>

      <fieldset className="medication-fieldset">
        <legend>Current medications <small>optional</small></legend>
        <div className="medication-list">{medicationOptions.map((medication) => <button type="button" key={medication} className={`medication-chip ${form.current_meds.includes(medication) ? "selected" : ""}`} onClick={() => toggleMedication(medication)} aria-pressed={form.current_meds.includes(medication)}>{medication}<span>{form.current_meds.includes(medication) ? "✓" : "+"}</span></button>)}</div>
      </fieldset>

      <div className="form-footer"><div className="privacy-note"><LockKeyhole size={14} /> Submitted to the configured clinical API only</div><Button className="primary-action" type="submit" disabled={loading || hasErrors}>{loading ? <><Loader2 className="spin" size={16} /> Analyzing patient…</> : <>Analyze patient <ArrowUpRight size={16} /></>}</Button></div>
    </form>
  );
}

