      {result.doctor_case && <div className="side-card doctor-card"><div className="side-card-head"><Stethoscope size={18} /><span>Doctor workflow</span></div><h3>Case ready for review</h3><div className="case-meta"><span>Case ID</span><strong>{result.doctor_case.case_id}</strong><span>Status</span><strong>{formatLabel(result.doctor_case.status)}</strong><span>Priority</span><strong>{formatLabel(result.doctor_case.priority)}</strong></div><p className="muted-note">The connected backend has created this case. Doctor actions are not available in the current API.</p></div>}
      <div className="side-card report-card"><div className="side-card-head"><FileText size={18} /><span>Health report</span></div><h3>{result.health_report.report_id}</h3><p>{result.health_report.disclaimer}</p><div className="report-foot"><Clock3 size={14} /> {result.health_report.case_status === "NOT_CREATED" ? "No doctor case created" : formatLabel(result.health_report.case_status)}</div></div>
    </aside></div>
    <div className="results-footer"><p><LockKeyhole size={14} /> This interface displays AI-assisted analysis. It does not provide a diagnosis or prescription.</p><Button variant="outline" onClick={onReset}><RefreshCw size={15} /> New analysis</Button></div>
